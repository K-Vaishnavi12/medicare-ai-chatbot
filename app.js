const emergencyKeys = ["emergency", "chest pain", "can't breathe", "cannot breathe", "suicide", "unconscious", "bleeding heavily", "stroke", "heart attack", "आपात", "అత్యవసర", "ఊపిరి", "సైడ్"];

let lang = localStorage.getItem("medicare-lang") || "en";

const messagesEl = document.getElementById("messages");
const suggestionsEl = document.getElementById("suggestions");
const form = document.getElementById("chatForm");
const input = document.getElementById("userInput");
const languageSelect = document.getElementById("language");
const clearBtn = document.getElementById("clearChat");

function t(key) {
  return ui[lang][key];
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.documentElement.lang = lang;
  languageSelect.value = lang;
  renderSuggestions();
}

function renderSuggestions() {
  suggestionsEl.innerHTML = "";
  t("suggestions").forEach((text) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "chip";
    btn.textContent = text;
    btn.addEventListener("click", () => {
      input.value = text;
      form.requestSubmit();
    });
    suggestionsEl.appendChild(btn);
  });
}

function addMessage(role, text) {
  const div = document.createElement("div");
  div.className = `msg ${role}`;
  const meta = document.createElement("span");
  meta.className = "meta";
  meta.textContent = role === "user" ? t("you") : t("bot");
  div.appendChild(meta);
  div.appendChild(document.createTextNode(text));
  messagesEl.appendChild(div);
  messagesEl.scrollTop = messagesEl.scrollHeight;
}

function addTyping() {
  const div = document.createElement("div");
  div.className = "msg bot";
  div.id = "typing";
  div.innerHTML = `<span class="meta">${t("bot")}</span><span class="typing"><i></i><i></i><i></i></span>`;
  messagesEl.appendChild(div);
  messagesEl.scrollTop = messagesEl.scrollHeight;
}

function removeTyping() {
  document.getElementById("typing")?.remove();
}

function normalize(text) {
  return text.toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, " ").replace(/\s+/g, " ").trim();
}

function answerFor(question) {
  const q = normalize(question);
  if (emergencyKeys.some((k) => q.includes(k.toLowerCase()))) {
    const urgent = knowledge[lang].find((item) => item.keys.some((k) => ["urgent", "emergency", "आपात", "అత్యవసర"].includes(k)))
      || knowledge.en.find((item) => item.keys.includes("urgent"));
    return urgent.answer;
  }

  const pool = [...knowledge[lang], ...(lang === "en" ? [] : knowledge.en)];
  let best = null;
  let bestScore = 0;

  for (const item of pool) {
    let score = 0;
    for (const key of item.keys) {
      const k = key.toLowerCase();
      if (q.includes(k)) score += k.length > 8 ? 4 : 2;
      else if (k.split(" ").every((part) => part.length > 2 && q.includes(part))) score += 1;
    }
    if (score > bestScore) {
      bestScore = score;
      best = item;
    }
  }

  if (best && bestScore > 0) return best.answer;
  return fallback[lang];
}

function resetChat() {
  messagesEl.innerHTML = "";
  addMessage("bot", t("welcome"));
}

form.addEventListener("submit", (e) => {
  e.preventDefault();
  const text = input.value.trim();
  if (!text) return;
  addMessage("user", text);
  input.value = "";
  addTyping();
  const reply = answerFor(text);
  setTimeout(() => {
    removeTyping();
    addMessage("bot", reply);
  }, 450 + Math.min(900, text.length * 8));
});

languageSelect.addEventListener("change", () => {
  lang = languageSelect.value;
  localStorage.setItem("medicare-lang", lang);
  applyI18n();
  resetChat();
});

clearBtn.addEventListener("click", resetChat);

applyI18n();
resetChat();
